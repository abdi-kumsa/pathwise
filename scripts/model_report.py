"""
Write docs/MODEL_COMPARISON.md and docs/FEATURE_IMPORTANCE.md from the model
outputs, so the documents always describe the models that are actually served.

    python scripts/model_report.py           # recompute, then write both docs
    python scripts/model_report.py --check   # exit 1 if either doc is stale

Recomputes the rolling-origin comparison (ml/compare_models.py) and the
post-training importance (ml/explain_predictions.py) first, so the numbers in
the docs and in ml/models/*.json come from the same run.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "ml"))

CMP_DOC = ROOT / "docs" / "MODEL_COMPARISON.md"
IMP_DOC = ROOT / "docs" / "FEATURE_IMPORTANCE.md"


def _fmt(v, digits=3):
    if v is None:
        return "—"
    if isinstance(v, float):
        if abs(v) >= 1000:
            return f"{v:,.0f}"
        return f"{v:.{digits}g}"
    return str(v)


def comparison_doc(result: dict) -> str:
    lines = [
        "# Model comparison (DOC1 step 4)",
        "",
        "Generated by `scripts/model_report.py` from `ml/models/ethiopia_comparison.json`. "
        "Do not edit by hand.",
        "",
        "Every Ethiopia forecast target is scored on a **rolling-origin backtest**: from each "
        "origin year (2019 onwards) every candidate forecasts 1–5 years ahead using only data up "
        "to that origin, and is scored against what was then observed. There is no random split.",
        "",
        "## Candidates",
        "",
        "| Candidate | What it does |",
        "|---|---|",
        "| `seasonal_naive` | Last observed value (baseline) |",
        "| `historical_mean` | Mean of the series up to the origin (baseline) |",
        "| `drift` | The series' own linear trend, extrapolated |",
        "| `pooled_ridge` | One ridge model shared by every series of a target: the change from the "
        "last value, from the latest change and the distance from the series' mean |",
        "",
        "The request path uses, at each horizon, the candidate with the lowest backtest RMSE. "
        "The choice is recorded on every forecast row as `selected_model`.",
        "",
        "Prediction intervals are the 5th–95th percentiles of the selected candidate's backtest "
        "residuals at that horizon. Their coverage is measured leave-one-origin-out: the "
        "percentiles from all other origins are applied to the held-out one.",
        "",
    ]
    for t in result["targets"]:
        lines += [f"## {t['id']} — {t['label']}", "",
                  f"Target `{t['target']}` on a {t['scale']} scale. {t['split']}. "
                  f"{t['n_holdout_rows']:,} backtest forecasts per candidate.", "",
                  "| Horizon | " + " | ".join(f"`{c}` RMSE" for c in t["candidates"])
                  + " | Selected | Skill vs naive | 90% interval coverage |",
                  "|---|" + "---|" * len(t["candidates"]) + "---|---|---|"]
        for h, cands in t["by_horizon"].items():
            sel = t["selected_by_horizon"].get(h)
            chosen = cands.get(sel, {})
            lines.append(
                f"| {h} | " + " | ".join(_fmt((cands.get(c) or {}).get("rmse")) for c in t["candidates"])
                + f" | `{sel}` | {_fmt(chosen.get('skill_vs_naive'))} | {_fmt(chosen.get('coverage'))} |"
            )
        lines.append("")
    lines += ["## Derived targets", "",
              "These DOC1 targets are computed from the estimated ones, not forecast separately.", "",
              "| Target | Derived from | Method |", "|---|---|---|"]
    for d in result.get("derived_targets", []):
        lines.append(f"| `{d['id']}` | `{d['derived_from']}` | {d['method']} |")
    lines += ["", "## What these numbers mean", "", result.get("accuracy_note", ""), "",
              "## Not compared", ""]
    lines += [f"- {m}" for m in result.get("us_models_not_compared", [])]
    lines += ["", "## How to run", "", "```text", "python scripts/model_report.py", "```", "",
              "Also served at `GET /api/methodology/model-comparison` (ADMIN).", ""]
    return "\n".join(lines)


def importance_doc(result: dict) -> str:
    lines = [
        "# Feature importance (DOC1 steps 5–6)",
        "",
        "Generated by `scripts/model_report.py` from `ml/models/ethiopia_feature_importance.json`. "
        "Do not edit by hand.",
        "",
        "Importance is computed **after training**, on the pooled ridge model the forecasts use "
        "(horizon 1), trained on earlier target years and explained on later ones. It is reported "
        "**separately** from the DOC1 collection priorities (PROC.S6), which are data-collection "
        "weights, not model weights, and are never blended with these figures.",
        "",
        "Three methods:",
        "",
        "- **model-based** — |coefficient × feature standard deviation|",
        "- **SHAP** — mean |coefficient × (x − mean x)|, which is exact SHAP for a linear model",
        "- **permutation** — increase in holdout RMSE when one feature is shuffled",
        "",
    ]
    for key, title in (("model1", "Model 1 — demand (applications)"),
                       ("model2", "Model 2 — employment")):
        b = result.get(key) or {}
        if not b.get("model_based"):
            continue
        lines += [f"## {title}", "",
                  f"Model `{b['model']}`, target `{b['target']}` ({b['scale']}). {b['split']}. "
                  f"{b['n_train']} training and {b['n_holdout']} holdout pairs.", "",
                  f"Holdout RMSE {_fmt(b['holdout_rmse'], 4)} against {_fmt(b['holdout_rmse_no_change'], 4)} "
                  "for predicting no change.", "",
                  "| Feature | Coefficient | Model-based | SHAP | Permutation |", "|---|---|---|---|---|"]
        mb = {r["feature"]: r["importance"] for r in b["model_based"]}
        sh = {r["feature"]: r["importance"] for r in b["shap"]}
        pm = {r["feature"]: r["importance"] for r in b["permutation"]}
        for f in sorted(mb, key=mb.get, reverse=True):
            lines.append(f"| `{f}` | {_fmt(b['coefficients'][f], 4)} | {_fmt(mb[f], 4)} | "
                         f"{_fmt(sh.get(f), 4)} | {_fmt(pm.get(f), 4)} |")
        lines += ["", f"Inputs: {b['features_from']}.", ""]
    lines += [
        "## Reading it",
        "",
        "A negative coefficient on `distance_from_series_mean` is mean reversion: a value above its "
        "own history tends to fall back. On the simulated data this is the dominant effect, as "
        "expected from a persistent series. Every other DOC1 column is collected but is not a "
        "learner input; the API lists them under `unused_by_learner`.",
        "",
        "Placement SHAP belongs to the leftover US model and appears only when it is switched on.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    from explain_predictions import ethiopia_feature_importance
    from ml.compare_models import compare_all

    docs = {
        CMP_DOC: comparison_doc(compare_all()),
        IMP_DOC: importance_doc(ethiopia_feature_importance(persist=True)),
    }
    stale = [p for p, text in docs.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if args.check:
        for p in stale:
            print(f"{p.relative_to(ROOT)} is stale — run python scripts/model_report.py", file=sys.stderr)
        return 1 if stale else 0
    for p, text in docs.items():
        p.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
