"""
Generate the API route table in docs/TECHNICAL.md from the running FastAPI app.

The table used to be maintained by hand and fell to about 40 of 117 routes.
This walks `main.app.routes`, reads each route's role guard from its
dependency tree (the `allowed` set captured by `require_roles`), and rewrites
the block between the markers:

    <!-- routes:start -->  ...  <!-- routes:end -->

Run inside the backend container, which has the backend dependencies:

    docker exec -w /app pathwise_backend python /scripts/gen_route_table.py --write

or, with backend requirements installed locally, from the repo root:

    python scripts/gen_route_table.py --write      # rewrite the doc
    python scripts/gen_route_table.py --check      # exit 1 if the doc is stale

`--check` is what CI runs, so a new route without a doc row fails the build.
"""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve()
ROOT = HERE.parents[1]
for candidate in (ROOT / "backend", Path("/app")):
    if (candidate / "main.py").exists() and str(candidate) not in sys.path:
        sys.path.insert(0, str(candidate))
        break

DOC_CANDIDATES = (ROOT / "docs" / "TECHNICAL.md", Path("/docs/TECHNICAL.md"))
START, END = "<!-- routes:start -->", "<!-- routes:end -->"


def _roles(dependant) -> tuple[set[str] | None, bool]:
    """(allowed roles or None, authenticated?) from a route's dependency tree."""
    allowed: set[str] | None = None
    authed = False
    stack = [dependant]
    while stack:
        dep = stack.pop()
        call = getattr(dep, "call", None)
        name = getattr(call, "__name__", "")
        if name == "get_current_user":
            authed = True
        closure = getattr(call, "__closure__", None) or ()
        free = getattr(getattr(call, "__code__", None), "co_freevars", ())
        for var, cell in zip(free, closure):
            if var == "allowed":
                try:
                    found = set(cell.cell_contents)
                except ValueError:
                    continue
                allowed = found if allowed is None else (allowed & found)
                authed = True
        stack.extend(getattr(dep, "dependencies", []) or [])
    return allowed, authed


def _api_routes(routes):
    """Every endpoint, flattening included routers.

    FastAPI <= 0.11x copied router routes onto the app as APIRoute objects.
    Newer FastAPI keeps each include as an `_IncludedRouter` and exposes the
    flattened endpoints through `effective_route_contexts()`; those carry the
    router-level dependencies too, which is where the role guards live.
    """
    for route in routes:
        contexts = getattr(route, "effective_route_contexts", None)
        if callable(contexts):
            yield from contexts()
        elif hasattr(route, "dependant") and hasattr(route, "endpoint"):
            yield route


def build_table() -> str:
    os.environ.setdefault("ENV", "dev")
    import main  # noqa: E402  (needs backend on sys.path)

    rows = []
    for route in _api_routes(main.app.routes):
        if not getattr(route, "include_in_schema", True):
            continue
        allowed, authed = _roles(route.dependant)
        if allowed:
            roles = ", ".join(sorted(allowed))
        elif authed:
            roles = "any signed-in role"
        else:
            roles = "public"
        summary = (route.summary or (route.endpoint.__doc__ or "").strip().split("\n")[0]).strip()
        summary = summary.replace("|", "\\|")[:110]
        for method in sorted(route.methods - {"HEAD", "OPTIONS"}):
            rows.append((route.path, method, roles, summary))
    rows.sort()

    legacy = getattr(main, "LEGACY_US_MODELS", False)
    lines = [
        START,
        "",
        f"Generated by `scripts/gen_route_table.py` from the running app — "
        f"{len(rows)} operations. Do not edit by hand.",
        "ADMIN satisfies every role guard. "
        + ("Leftover US-model routes are **included** (LEGACY_US_MODELS=1)."
           if legacy else
           "Leftover US-model routes (`/api/market`, `/api/enrollment`, "
           "`/api/recommendations`) are **not listed**: they exist only when "
           "the API runs with `LEGACY_US_MODELS=1`."),
        "",
        "| Method | Path | Roles | Summary |",
        "|---|---|---|---|",
    ]
    lines += [f"| {m} | `{p}` | {r} | {s} |" for p, m, r, s in rows]
    lines += ["", END]
    return "\n".join(lines)


def main_cli() -> int:
    ap = argparse.ArgumentParser()
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--print", action="store_true")
    args = ap.parse_args()

    table = build_table()
    if args.print:
        print(table)
        return 0

    doc = next((p for p in DOC_CANDIDATES if p.exists()), None)
    if doc is None:
        print("docs/TECHNICAL.md not found", file=sys.stderr)
        return 2
    text = doc.read_text(encoding="utf-8")
    if START not in text or END not in text:
        print(f"markers {START} / {END} missing from {doc}", file=sys.stderr)
        return 2
    before, rest = text.split(START, 1)
    _, after = rest.split(END, 1)
    updated = before + table + after

    if args.check:
        if updated != text:
            print("docs/TECHNICAL.md route table is stale. Run: "
                  "python scripts/gen_route_table.py --write", file=sys.stderr)
            return 1
        print("route table up to date")
        return 0

    doc.write_text(updated, encoding="utf-8", newline="\n")
    print(f"wrote {table.count(chr(10)) - 7} rows to {doc}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main_cli())
